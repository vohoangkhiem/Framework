/**
 * Enforces Conventional Commits (https://www.conventionalcommits.org) without an extra dependency.
 * Invoked by the Husky `commit-msg` hook with the path to the commit message file.
 *
 * Accepted examples:
 *   feat(cart): add API-based cart seeding
 *   fix: handle "Product added." alert for logged-in users
 *   chore(deps)!: upgrade Playwright to 1.61
 */
const fs = require('fs');

const TYPES = [
  'feat',
  'fix',
  'docs',
  'style',
  'refactor',
  'perf',
  'test',
  'build',
  'ci',
  'chore',
  'revert',
];
const HEADER_PATTERN = new RegExp(`^(${TYPES.join('|')})(\\([\\w\\-./]+\\))?!?: .{1,100}$`);

const messageFile = process.argv[2];
if (!messageFile) {
  console.error('[commit-msg] Missing commit message file argument.');
  process.exit(1);
}

const header = fs.readFileSync(messageFile, 'utf8').split(/\r?\n/)[0].trim();

// Merge / revert commits generated by git are always accepted.
if (/^(Merge|Revert) /.test(header) || HEADER_PATTERN.test(header)) {
  process.exit(0);
}

console.error(`
[commit-msg] Invalid commit message header:
  "${header}"

Expected format: <type>(<optional scope>)<optional !>: <description>
Allowed types:   ${TYPES.join(', ')}
Example:         feat(checkout): validate order confirmation amount
`);
process.exit(1);
